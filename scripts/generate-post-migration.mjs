// Emits a Netlify DB migration that syncs the live posts table to content/posts.mjs.
//
//   node scripts/generate-post-migration.mjs <migration_name>
//
// Writes netlify/database/migrations/<timestamp>_<name>/migration.sql, then review
// the SQL before committing. Read time is computed from the body rather than typed
// by hand, so it can't drift from what the post actually is (brand/CONTENT-POLICY.md
// requires an honest number).

import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { posts } from '../content/posts.mjs';

const MIGRATIONS_DIR = 'netlify/database/migrations';

// Migrations apply in filename order, and existing folders are stamped by hand,
// so a wall-clock timestamp can sort *before* migrations that already ran. Take
// the later of "now" and one second past the newest existing stamp.
function nextStamp() {
  const now = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14);
  const newest = readdirSync(MIGRATIONS_DIR)
    .map((entry) => entry.slice(0, 14))
    .filter((stamp) => /^\d{14}$/.test(stamp))
    .sort()
    .pop();
  if (!newest || now > newest) return now;
  return String(BigInt(newest) + 1n);
}

const WORDS_PER_MINUTE = 200;

export const readTime = (content) =>
  Math.max(2, Math.round(content.trim().split(/\s+/).length / WORDS_PER_MINUTE));

// Postgres string literal: double every embedded single quote.
const q = (value) => `'${String(value).replace(/'/g, "''")}'`;

function generate(name) {
  const dir = `${MIGRATIONS_DIR}/${nextStamp()}_${name}`;

  const statements = posts.map((post) => `
UPDATE posts SET
  title = ${q(post.title)},
  excerpt = ${q(post.excerpt)},
  content = ${q(post.content)},
  tags = ${q(post.tags)},
  read_time = ${readTime(post.content)},
  updated_at = now()
WHERE slug = ${q(post.slug)};
`).join('');

  const sql = `-- Generated by scripts/generate-post-migration.mjs from content/posts.mjs.
-- Do not hand-edit: regenerate instead, so the file and the database cannot diverge.
--
-- Rewrites the body of every post in content/posts.mjs, matched by slug.
-- published_at is deliberately untouched, so revising a post does not change its
-- publication date or its position in the feed. Idempotent: re-running sets the
-- same values.
${statements}`;

  mkdirSync(dir, { recursive: true });
  writeFileSync(`${dir}/migration.sql`, sql);
  console.log(`Wrote ${dir}/migration.sql (${posts.length} posts)`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const name = process.argv[2];
  if (!name) {
    console.error('Usage: node scripts/generate-post-migration.mjs <migration_name>');
    process.exit(1);
  }
  generate(name);
}
