// Encrypt a paid skill .zip into a bundled module the download function can read.
// The repo is public, so paid files are only ever committed encrypted.
//
//   SKILL_ENCRYPTION_KEY=<64 hex chars> node scripts/encrypt-paid-skill.mjs <sku> <path/to/skill.zip>
//
// Writes netlify/lib/paid-skills/<sku>.enc.js. Set the same SKILL_ENCRYPTION_KEY
// as a secret environment variable on Netlify (scope: Functions).
import { createCipheriv, randomBytes } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [sku, zipPath] = process.argv.slice(2);
const keyHex = process.env.SKILL_ENCRYPTION_KEY || '';
if (!sku || !zipPath) throw new Error('usage: node scripts/encrypt-paid-skill.mjs <sku> <zip>');
if (!/^[0-9a-f]{64}$/i.test(keyHex)) throw new Error('SKILL_ENCRYPTION_KEY must be 64 hex characters');

const iv = randomBytes(12);
const cipher = createCipheriv('aes-256-gcm', Buffer.from(keyHex, 'hex'), iv);
const data = Buffer.concat([cipher.update(readFileSync(zipPath)), cipher.final()]);
const payload = Buffer.concat([iv, cipher.getAuthTag(), data]).toString('base64');
writeFileSync(`netlify/lib/paid-skills/${sku}.enc.js`,
  `// Encrypted with AES-256-GCM (iv | tag | ciphertext). Generated by scripts/encrypt-paid-skill.mjs.\nexport default ${JSON.stringify(payload)};\n`);
console.log(`wrote netlify/lib/paid-skills/${sku}.enc.js (${payload.length} chars)`);
