// Encrypt every paid skill .zip in a folder in one go (one key for all of them).
//
//   SKILL_ENCRYPTION_KEY=<64 hex chars> node scripts/encrypt-all-paid-skills.mjs <folder-with-zips>
//
// Each <sku>.zip becomes netlify/lib/paid-skills/<sku>.enc.js. Only SKUs listed in
// src/lib/paidSkills.js are encrypted (anything else in the folder is reported and skipped),
// so a stray or free zip never gets committed. Uses the same AES-256-GCM format as
// scripts/encrypt-paid-skill.mjs and the same SKILL_ENCRYPTION_KEY Netlify already has.
import { createCipheriv, randomBytes } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { PAID_SKILLS } from '../src/lib/paidSkills.js';

const dir = process.argv[2];
const keyHex = process.env.SKILL_ENCRYPTION_KEY || '';
if (!dir) throw new Error('usage: node scripts/encrypt-all-paid-skills.mjs <folder-with-zips>');
if (!/^[0-9a-f]{64}$/i.test(keyHex)) throw new Error('SKILL_ENCRYPTION_KEY must be 64 hex characters');

const zips = readdirSync(dir).filter((f) => f.endsWith('.zip'));
let done = 0;
for (const f of zips) {
  const sku = basename(f, '.zip');
  if (!PAID_SKILLS[sku]) { console.log(`skip  ${f} (not in PAID_SKILLS)`); continue; }
  const iv = randomBytes(12);
  const cipher = createCipheriv('aes-256-gcm', Buffer.from(keyHex, 'hex'), iv);
  const data = Buffer.concat([cipher.update(readFileSync(join(dir, f))), cipher.final()]);
  const payload = Buffer.concat([iv, cipher.getAuthTag(), data]).toString('base64');
  writeFileSync(`netlify/lib/paid-skills/${sku}.enc.js`,
    `// Encrypted with AES-256-GCM (iv | tag | ciphertext). Generated by scripts/encrypt-all-paid-skills.mjs.\nexport default ${JSON.stringify(payload)};\n`);
  console.log(`wrote netlify/lib/paid-skills/${sku}.enc.js`);
  done += 1;
}
const missing = Object.keys(PAID_SKILLS).filter((s) => !zips.includes(`${s}.zip`));
console.log(`\n${done} encrypted.` + (missing.length ? ` No zip in the folder for: ${missing.join(', ')} (fine if already encrypted).` : ''));
